"""
Hidden Markov Model (HMM) Classifier for ECG Arrhythmia Detection.

Theoretical & Biological Foundation:
An ECG heartbeat is an inherently non-stationary biological sequence generated by
the sequential electrical activation of cardiac tissue:
- State 0: Atrial Depolarization (P-wave)
- State 1: AV Conduction Delay (PR-segment)
- State 2: Ventricular Depolarization (QRS-complex)
- State 3: Plateau & Early Repolarization (ST-segment)
- State 4: Ventricular Repolarization (T-wave)

Model Architecture:
Implements Class-Conditional Continuous Gaussian HMMs:
- For each AAMI class c in {N, S, V, F, Q}, an independent Gaussian HMM lambda_c = (A_c, B_c, pi_c)
  is trained via the Baum-Welch (EM) algorithm on observation sequences from that class.
- Forward algorithm evaluates the exact log-likelihood log P(O | lambda_c) for an unseen beat.
- Classification is performed using Maximum A Posteriori (MAP) with balanced or empirical priors.
- Viterbi algorithm decodes the optimal hidden state sequence for clinical interpretability.
"""

import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any, Union
import numpy as np
import joblib
from hmmlearn import hmm

# Allow running as a standalone script or module
sys.path.append(str(Path(__file__).resolve().parent.parent))
from src.config import (
    AAMI_CLASSES,
    CLASS_TO_IDX,
    IDX_TO_CLASS,
    HMM_N_STATES,
    HMM_N_FRAMES,
    HMM_COVAR_TYPE,
    HMM_N_ITER,
    HMM_MIN_COVAR,
    RANDOM_SEED,
    MODELS_DIR,
)


class ClassConditionalHMM:
    """
    Class-Conditional Hidden Markov Model for multi-class ECG heartbeat classification.
    """

    def __init__(
        self,
        n_states: int = HMM_N_STATES,
        n_frames: int = HMM_N_FRAMES,
        covariance_type: str = HMM_COVAR_TYPE,
        n_iter: int = HMM_N_ITER,
        min_covar: float = HMM_MIN_COVAR,
        classes: List[str] = AAMI_CLASSES,
        random_state: int = RANDOM_SEED
    ):
        """
        Parameters
        ----------
        n_states : int
            Number of hidden states per class HMM (default: 5 states).
        n_frames : int
            Number of temporal observation frames per beat (default: 11).
        covariance_type : str
            Covariance matrix type: 'diag', 'spherical', or 'full'.
        n_iter : int
            Maximum Baum-Welch (EM) iterations per class model.
        min_covar : float
            Regularization floor for covariance diagonals to prevent singularity.
        classes : List[str]
            Target classification categories (['N', 'S', 'V', 'F', 'Q']).
        random_state : int
            Random seed for reproducible EM initialization.
        """
        self.n_states = n_states
        self.n_frames = n_frames
        self.covariance_type = covariance_type
        self.n_iter = n_iter
        self.min_covar = min_covar
        self.classes = classes
        self.random_state = random_state

        # Dictionary holding the trained GaussianHMM for each class
        self.models: Dict[str, hmm.GaussianHMM] = {}
        # Class prior probabilities log P(c)
        self.class_priors: Dict[str, float] = {}
        self.is_fitted = False

    def _init_model(self) -> hmm.GaussianHMM:
        """
        Instantiate a GaussianHMM with Left-to-Right topology initialization.
        """
        model = hmm.GaussianHMM(
            n_components=self.n_states,
            covariance_type=self.covariance_type,
            n_iter=self.n_iter,
            min_covar=self.min_covar,
            random_state=self.random_state,
            init_params="stmc",
            params="stmc",
            implementation="log"
        )
        return model

    def fit(
        self,
        X_seq: np.ndarray,
        lengths: List[int],
        y_labels: List[str],
        balanced_priors: bool = True,
        max_samples_per_class: int = 5000
    ) -> "ClassConditionalHMM":
        """
        Train class-conditional HMMs using the Baum-Welch (EM) algorithm.

        Parameters
        ----------
        X_seq : np.ndarray
            Observation vectors concatenated across beats, shape (N_beats * n_frames, n_features).
        lengths : List[int]
            List where each entry is the length of one beat sequence (n_frames).
        y_labels : List[str]
            List of class labels ('N', 'S', 'V', 'F', 'Q') for each heartbeat.
        balanced_priors : bool
            If True, assigns uniform prior P(c) = 1 / K.
            If False, uses empirical frequency priors.
        max_samples_per_class : int
            Subsampling limit for dominant classes (e.g. N) to balance training time
            and prevent excessive majority class bias on an i5 CPU.

        Returns
        -------
        ClassConditionalHMM
            Self reference.
        """
        y_array = np.array(y_labels)
        n_beats = len(lengths)
        total_obs = len(X_seq)

        print(f"[HMM] Training Class-Conditional Gaussian HMMs on {n_beats:,} heartbeat sequences...")
        print(f"      Hidden States: {self.n_states} | Observation Frames: {self.n_frames} | Covariance: {self.covariance_type}")

        # Map each beat to its slice in X_seq
        # Since lengths is constant (n_frames per beat), beat i corresponds to:
        # [i * n_frames : (i + 1) * n_frames]
        
        for c in self.classes:
            beat_indices = np.where(y_array == c)[0]
            n_class_beats = len(beat_indices)

            if n_class_beats == 0:
                print(f"[HMM] WARNING: No training samples found for class '{c}'! Skipping model.")
                continue

            # Subsample if class exceeds limit (especially Normal 'N' beats)
            if n_class_beats > max_samples_per_class:
                rng = np.random.RandomState(self.random_state)
                selected_indices = rng.choice(beat_indices, size=max_samples_per_class, replace=False)
            else:
                selected_indices = beat_indices

            # Extract observation sub-matrix and lengths for this class
            class_lengths = [self.n_frames] * len(selected_indices)
            class_slices = []
            for b_idx in selected_indices:
                start = b_idx * self.n_frames
                end = start + self.n_frames
                class_slices.append(X_seq[start:end])

            X_class = np.vstack(class_slices)

            print(f"  --> Training HMM for Class '{c}' with {len(selected_indices):,} beats ({len(X_class):,} frames)...", end=" ", flush=True)
            model = self._init_model()
            
            try:
                model.fit(X_class, class_lengths)
                self.models[c] = model
                print("Converged.")
            except Exception as e:
                print(f"FAILED ({e})")

        # Compute priors
        if balanced_priors:
            uniform_prior = 1.0 / len(self.models)
            self.class_priors = {c: np.log(uniform_prior) for c in self.models.keys()}
        else:
            total_trained = sum(len(np.where(y_array == c)[0]) for c in self.models.keys())
            self.class_priors = {
                c: np.log(len(np.where(y_array == c)[0]) / total_trained)
                for c in self.models.keys()
            }

        self.is_fitted = True
        print(f"[HMM] Successfully trained {len(self.models)} class-conditional HMM models.")
        return self

    def predict_log_likelihoods(
        self,
        X_seq: np.ndarray,
        lengths: List[int]
    ) -> np.ndarray:
        """
        Evaluate log P(O | lambda_c) for each class model across all test beats.

        Parameters
        ----------
        X_seq : np.ndarray
            Observation matrix of shape (N_beats * n_frames, n_features).
        lengths : List[int]
            Sequence lengths per beat.

        Returns
        -------
        np.ndarray
            Log-likelihood matrix of shape (N_beats, N_classes).
        """
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before computing likelihoods.")

        n_beats = len(lengths)
        n_classes = len(self.classes)
        log_likes = np.full((n_beats, n_classes), -np.inf, dtype=np.float64)

        # Pre-slice each beat sequence
        beat_sequences = []
        for i in range(n_beats):
            start = i * self.n_frames
            end = start + self.n_frames
            beat_sequences.append(X_seq[start:end])

        # Evaluate log-likelihoods for each class
        for c_idx, c in enumerate(self.classes):
            if c not in self.models:
                continue
            model = self.models[c]

            for b_idx in range(n_beats):
                try:
                    # hmmlearn's score(X) evaluates the total log-likelihood of observation sequence X
                    ll = model.score(beat_sequences[b_idx])
                    # Guard against non-finite scores
                    if np.isnan(ll) or np.isneginf(ll):
                        ll = -1e6
                    log_likes[b_idx, c_idx] = ll
                except Exception:
                    log_likes[b_idx, c_idx] = -1e6

        return log_likes

    def predict(
        self,
        X_seq: np.ndarray,
        lengths: List[int],
        use_priors: bool = True
    ) -> List[str]:
        """
        Predict AAMI heartbeat class using Maximum A Posteriori (MAP) scoring:
        y_hat = argmax_c [ log P(O | lambda_c) + log P(c) ]

        Parameters
        ----------
        X_seq : np.ndarray
            Observation matrix.
        lengths : List[int]
            Sequence lengths.
        use_priors : bool
            Whether to include class prior probabilities.

        Returns
        -------
        List[str]
            Predicted class names (e.g. ['N', 'V', ...]).
        """
        log_likes = self.predict_log_likelihoods(X_seq, lengths)

        if use_priors:
            for c_idx, c in enumerate(self.classes):
                if c in self.class_priors:
                    log_likes[:, c_idx] += self.class_priors[c]

        best_indices = np.argmax(log_likes, axis=1)
        predictions = [self.classes[idx] for idx in best_indices]
        return predictions

    def predict_proba(
        self,
        X_seq: np.ndarray,
        lengths: List[int]
    ) -> np.ndarray:
        """
        Compute normalized posterior probabilities P(c | O) via Softmax.

        Returns
        -------
        np.ndarray
            Probability array of shape (N_beats, N_classes).
        """
        log_likes = self.predict_log_likelihoods(X_seq, lengths)
        for c_idx, c in enumerate(self.classes):
            if c in self.class_priors:
                log_likes[:, c_idx] += self.class_priors[c]

        # Stable softmax
        max_log = np.max(log_likes, axis=1, keepdims=True)
        exp_vals = np.exp(log_likes - max_log)
        probs = exp_vals / np.sum(exp_vals, axis=1, keepdims=True)
        return probs

    def decode_hidden_states(
        self,
        single_beat_obs: np.ndarray,
        class_name: str = "N"
    ) -> Tuple[float, np.ndarray]:
        """
        Decode the most likely sequence of hidden states using the Viterbi algorithm.

        Parameters
        ----------
        single_beat_obs : np.ndarray
            Observation matrix for one beat of shape (n_frames, n_features).
        class_name : str
            Which class HMM model to use for decoding.

        Returns
        -------
        Tuple[float, np.ndarray]
            (viterbi_log_prob, state_sequence)
        """
        if class_name not in self.models:
            raise ValueError(f"Model for class '{class_name}' is not available.")
        model = self.models[class_name]
        viterbi_ll, state_seq = model.decode(single_beat_obs, algorithm="viterbi")
        return viterbi_ll, state_seq

    def save(self, filepath: Path) -> None:
        """Serialize model to disk."""
        filepath = Path(filepath)
        filepath.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(self, filepath)
        print(f"[HMM] Model saved to models/{filepath.name}")

    @classmethod
    def load(cls, filepath: Path) -> "ClassConditionalHMM":
        """Deserialize model from disk."""
        filepath = Path(filepath)
        model = joblib.load(filepath)
        print(f"[HMM] Model loaded from models/{filepath.name}")
        return model
